#!/usr/bin/env python3
"""Make init/var-skel.h: the directory skeleton of iOS 26's data volume (/private/var).

On a real iPhone /private/var is the Data volume, laid down at restore from the
rootfs's private/var. Here it is ramfs, empty at every boot, so init26 recreates
the skeleton before it starts Apple's launchd: every directory and symbolic link
the IPSW's rootfs has under private/var (owner, group, mode), except
staged_system_apps (the apps installed at first boot, ~1 GB). Regular files (42,
0.6 MB, mostly MobileAsset samples) are not carried.

Usage: gen-var-skel.py extract/rootfs.slt init/var-skel.h
"""
import sys

slt, out = sys.argv[1], sys.argv[2]


def mode_bits(s):
    """'drwx--x--x' / 'drwxrwxrwt' -> permission bits (with setuid/setgid/sticky)."""
    bits = 0
    for i, (ch, val) in enumerate(zip(s[1:10], (0o400, 0o200, 0o100, 0o40, 0o20, 0o10, 4, 2, 1))):
        if ch not in '-':
            bits |= val
        if i == 2 and ch in 'sS':
            bits |= 0o4000
        if i == 5 and ch in 'sS':
            bits |= 0o2000
        if i == 8 and ch in 'tT':
            bits |= 0o1000
    return bits


entries, cur = [], {}


def flush():
    p = cur.get('Path', '')
    if not p.startswith('private/var/') or p.startswith('private/var/staged_system_apps'):
        return
    m = cur.get('Mode', '')
    if not m or m[0] not in 'dl':
        return
    uid = int(cur.get('User ID') or 0)
    gid = int(cur.get('Group ID') or 0)
    target = cur.get('Symbolic Link', '') if m[0] == 'l' else ''
    entries.append((p.count('/'), p[len('private/var'):], m[0], mode_bits(m), uid, gid, target))


for line in open(slt, encoding='utf-8', errors='replace'):
    line = line.rstrip('\n')
    if not line:
        if cur:
            flush()
            cur = {}
        continue
    if ' = ' in line:
        k, v = line.split(' = ', 1)
        cur[k] = v
if cur:
    flush()

entries.sort()


def c(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


with open(out, 'w') as f:
    f.write('/* generated by scripts/gen-var-skel.py from the IPSW rootfs listing: do not edit */\n')
    f.write('struct var_skel { const char *path; char type; int mode, uid, gid; const char *target; };\n')
    f.write('static const struct var_skel VAR_SKEL[] = {\n')
    for _, path, t, mode, uid, gid, target in entries:
        f.write('\t{ %s, %s, 0%o, %d, %d, %s },\n' % (c(path), repr(t), mode, uid, gid, c(target)))
    f.write('\t{ 0, 0, 0, 0, 0, 0 }\n};\n')
print('%s: %d entries' % (out, len(entries)))
